#!/usr/bin/env python3
"""policy-generator — tailor ISO 27001 / SOC 2-aligned security policies from a profile.

Flow:  profile.yaml + templates/  ->  fill placeholders (deterministic)  ->
       LLM tailor the body (optional, with a complete deterministic fallback)  ->
       output/<policy>.md  +  output/<policy>.docx

Every output is labelled an AI-assisted draft that a human must review and approve.
"""
import argparse
import datetime as _dt
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
TEMPLATES_DIR = ROOT / "templates"

# policy key -> (title, template filename). Order is the default generation order.
POLICIES = {
    "information-security-policy": ("Information Security Policy", "information-security-policy.md"),
    "access-control": ("Access Control Policy", "access-control.md"),
    "acceptable-use": ("Acceptable Use Policy", "acceptable-use.md"),
    "data-classification": ("Data Classification & Handling Policy", "data-classification.md"),
    "incident-response": ("Incident Response Policy", "incident-response.md"),
    "business-continuity": ("Business Continuity & Disaster Recovery Policy", "business-continuity.md"),
    "vendor-risk": ("Vendor & Third-Party Risk Policy", "vendor-risk.md"),
    "change-management": ("Change Management Policy", "change-management.md"),
}

BANNER = (
    "> **AI-ASSISTED DRAFT — NOT YET APPROVED.** Generated by `policy-generator`. "
    "This document must be reviewed, edited where needed, and formally approved by "
    "{company_name} before it takes effect. It is a drafting aid for your GRC team, "
    "not legal, audit, or compliance advice."
)

FOOTER = ("AI-assisted draft — requires review and approval by {company_name} before use. "
          "Page content is a drafting aid, not a compliance attestation.")

TAILOR_SYSTEM = (
    "You are a GRC policy writer tailoring an information-security policy draft to one "
    "company. Rules: keep EVERY Markdown heading (lines starting with #) exactly as given, "
    "in the same order. Do not add, remove, or renumber headings. Expand the body text under "
    "each heading into concrete, specific policy language for this company, using its "
    "industry, size, cloud providers, data types, and frameworks. Resolve any bracketed "
    "placeholders sensibly. Return only the Markdown document — no commentary, no code fences."
)


# ---------------------------------------------------------------------------
# profile + placeholders
# ---------------------------------------------------------------------------
def load_profile(path):
    with open(path, "r", encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    return data


def _join(v):
    if isinstance(v, (list, tuple)):
        return ", ".join(str(x) for x in v)
    return str(v)


def flatten_profile(profile):
    """Profile dict -> flat {placeholder: string} map used for {{...}} substitution."""
    c = profile.get("company", {}) if isinstance(profile, dict) else {}
    today = _dt.date.today().isoformat()
    values = {
        "company_name": c.get("name", ""),
        "industry": c.get("industry", ""),
        "company_size": _join(c.get("size", "")),
        "cloud_providers": _join(c.get("cloud_providers", "")),
        "data_types": _join(c.get("data_types", "")),
        "frameworks": _join(c.get("frameworks", "")),
        "security_contact": c.get("security_contact", ""),
        "policy_owner": c.get("policy_owner", "Information Security Officer"),
        "approver": c.get("approver", "Executive Management"),
        "date": profile.get("date", today) if isinstance(profile, dict) else today,
        "version": profile.get("version", "0.1 (Draft)") if isinstance(profile, dict) else "0.1 (Draft)",
    }
    return {k: str(v) for k, v in values.items()}


_PLACEHOLDER = re.compile(r"\{\{\s*([a-zA-Z0-9_]+)\s*\}\}")


def substitute(text, values):
    """Replace {{key}} with values. Unknown/blank keys become a visible [REVIEW: key]
    marker so the gap is obvious to the human reviewer. Returns (text, missing_keys)."""
    missing = []

    def repl(m):
        key = m.group(1)
        val = values.get(key, "")
        if not val:
            if key not in missing:
                missing.append(key)
            return f"[REVIEW: {key}]"
        return val

    return _PLACEHOLDER.sub(repl, text), missing


# ---------------------------------------------------------------------------
# selection + templates
# ---------------------------------------------------------------------------
def select_policies(profile, requested=None):
    """Resolve which policy keys to generate.
    Priority: explicit `requested` (CLI) > profile['policies'] > all."""
    valid = list(POLICIES)
    if requested in ("all", ["all"]):
        chosen = valid
    elif requested in (None, []):
        chosen = (profile.get("policies") if isinstance(profile, dict) else None) or valid
    else:
        chosen = requested
    unknown = [k for k in chosen if k not in POLICIES]
    if unknown:
        raise ValueError(
            f"Unknown policy key(s): {', '.join(unknown)}. Valid keys: {', '.join(valid)}"
        )
    # keep canonical order, dedupe
    return [k for k in valid if k in set(chosen)]


def load_template(key):
    title, fname = POLICIES[key]
    path = TEMPLATES_DIR / fname
    return path.read_text(encoding="utf-8")


# ---------------------------------------------------------------------------
# tailoring
# ---------------------------------------------------------------------------
def _headings(md):
    return [ln.strip() for ln in md.splitlines() if ln.lstrip().startswith("#")]


def _split_header_body(md):
    """Split filled template into (header, body): header is everything before the
    first '## ' section heading (title + mapping + owner line); body is the rest."""
    lines = md.splitlines()
    for i, ln in enumerate(lines):
        if ln.lstrip().startswith("## "):
            return "\n".join(lines[:i]).rstrip(), "\n".join(lines[i:]).strip()
    return md.rstrip(), ""


def tailor(body_md, profile, llm=None, no_llm=False):
    """Expand the body via the LLM. Returns (text, used_llm).
    Falls back to the deterministic filled body on any failure or malformed output,
    so the result is always a complete policy."""
    if no_llm or not body_md.strip():
        return body_md, False
    if llm is None:
        import llm as _llm  # imported lazily so tests never need the module live
        llm = _llm.complete
    c = profile.get("company", {}) if isinstance(profile, dict) else {}
    context = (
        f"Company: {c.get('name','')}\nIndustry: {c.get('industry','')}\n"
        f"Size: {_join(c.get('size',''))}\nCloud: {_join(c.get('cloud_providers',''))}\n"
        f"Data types: {_join(c.get('data_types',''))}\nFrameworks: {_join(c.get('frameworks',''))}\n"
    )
    prompt = f"{context}\n---\nTailor this policy body for the company above:\n\n{body_md}"
    try:
        out = llm(prompt, system=TAILOR_SYSTEM)
    except Exception:
        return body_md, False
    if not out or not out.strip():
        return body_md, False
    out = re.sub(r"^```[a-zA-Z]*\n|\n```$", "", out.strip())  # strip stray code fences
    # structural guard: the model must have kept every heading, else we don't trust it.
    want = set(_headings(body_md))
    have = set(_headings(out))
    if not want.issubset(have):
        return body_md, False
    return out.strip(), True


# ---------------------------------------------------------------------------
# document assembly
# ---------------------------------------------------------------------------
def approval_table_md(values):
    return (
        "## Document Control\n\n"
        "| Field | Value |\n|---|---|\n"
        f"| Version | {values['version']} |\n"
        f"| Date | {values['date']} |\n"
        f"| Owner | {values['policy_owner']} |\n"
        f"| Approver | {values['approver']} |\n"
        "| Status | Draft — pending human review and approval |\n"
    )


def build_document(key, profile, llm=None, no_llm=False):
    """Returns (markdown_text, used_llm) for one policy — fully assembled and labelled."""
    values = flatten_profile(profile)
    filled, _missing = substitute(load_template(key), values)
    header, body = _split_header_body(filled)
    tailored_body, used = tailor(body, profile, llm=llm, no_llm=no_llm)
    banner = BANNER.format(**values)
    footer_note = "\n---\n\n*" + FOOTER.format(**values) + "*\n"
    parts = [header, banner, approval_table_md(values), tailored_body, footer_note]
    md = "\n\n".join(p.strip() for p in parts if p.strip()) + "\n"
    return md, used


# ---------------------------------------------------------------------------
# docx rendering (markdown subset -> python-docx)
# ---------------------------------------------------------------------------
def _add_runs(paragraph, text):
    """Render inline **bold** and `code` as runs."""
    for i, chunk in enumerate(re.split(r"(\*\*[^*]+\*\*|`[^`]+`)", text)):
        if not chunk:
            continue
        if chunk.startswith("**") and chunk.endswith("**"):
            paragraph.add_run(chunk[2:-2]).bold = True
        elif chunk.startswith("`") and chunk.endswith("`"):
            run = paragraph.add_run(chunk[1:-1])
            run.font.name = "Consolas"
        else:
            paragraph.add_run(chunk)


def md_to_docx(md, out_path, footer_text):
    """Render the assembled markdown to a .docx. Handles the subset used by the
    templates: #/##/###/#### headings, > blockquotes, - bullets, 1. numbers, and
    | pipe | tables. Anything else becomes a plain paragraph (robust to LLM output)."""
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    lines = md.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s:
            i += 1
            continue
        # tables: a run of | ... | lines
        if s.startswith("|") and s.endswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                if not re.match(r"^[:\-\s|]+$", lines[i].strip().strip("|")):  # skip --- separator
                    rows.append(cells)
                i += 1
            if rows:
                ncol = max(len(r) for r in rows)
                table = doc.add_table(rows=0, cols=ncol)
                table.style = "Table Grid"
                for r_idx, row in enumerate(rows):
                    cells = table.add_row().cells
                    for c_idx in range(ncol):
                        cells[c_idx].text = row[c_idx] if c_idx < len(row) else ""
                    if r_idx == 0:
                        for cell in cells:
                            for p in cell.paragraphs:
                                for run in p.runs:
                                    run.bold = True
            continue
        # headings
        m = re.match(r"^(#{1,4})\s+(.*)$", s)
        if m:
            level = len(m.group(1)) - 1  # # -> 0 (Title), ## -> 1, ...
            doc.add_heading(m.group(2).strip(), level=min(level, 4))
            i += 1
            continue
        # blockquote (AI banner / mapping note)
        if s.startswith(">"):
            text = s.lstrip("> ").strip()
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Pt(12)
            _add_runs(p, text)
            for run in p.runs:
                run.italic = True
            i += 1
            continue
        # horizontal rule
        if re.match(r"^-{3,}$|^\*{3,}$", s):
            i += 1
            continue
        # bullet / numbered list
        if s.startswith(("- ", "* ")):
            _add_runs(doc.add_paragraph(style="List Bullet"), s[2:].strip())
            i += 1
            continue
        mnum = re.match(r"^\d+\.\s+(.*)$", s)
        if mnum:
            _add_runs(doc.add_paragraph(style="List Number"), mnum.group(1).strip())
            i += 1
            continue
        # plain paragraph
        _add_runs(doc.add_paragraph(), s)
        i += 1

    # real page footer on every page
    footer_para = doc.sections[0].footer.paragraphs[0]
    footer_para.text = footer_text
    for run in footer_para.runs:
        run.italic = True
        run.font.size = Pt(8)

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(out_path))
    return out_path


# ---------------------------------------------------------------------------
# driver
# ---------------------------------------------------------------------------
def generate(profile, keys, out_dir, llm=None, no_llm=False):
    """Generate .md + .docx for each key. Returns list of (key, md_path, docx_path, used_llm)."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    values = flatten_profile(profile)
    results = []
    for key in keys:
        md, used = build_document(key, profile, llm=llm, no_llm=no_llm)
        md_path = out_dir / f"{key}.md"
        md_path.write_text(md, encoding="utf-8")
        docx_path = out_dir / f"{key}.docx"
        md_to_docx(md, docx_path, FOOTER.format(**values))
        results.append((key, md_path, docx_path, used))
    return results


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate tailored security policies from a company profile.")
    ap.add_argument("--profile", default=str(ROOT / "profile.example.yaml"), help="Path to profile YAML.")
    ap.add_argument("--policies", default=None,
                    help="Comma-separated policy keys, or 'all'. Default: profile's list, else all.")
    ap.add_argument("--out", default=str(ROOT / "output"), help="Output directory.")
    ap.add_argument("--no-llm", action="store_true", help="Skip the LLM; deterministic fill only.")
    ap.add_argument("--list", action="store_true", help="List available policy keys and exit.")
    args = ap.parse_args(argv)

    if args.list:
        print("Available policies:")
        for k, (title, _) in POLICIES.items():
            print(f"  {k:28s} {title}")
        return 0

    profile = load_profile(args.profile)
    requested = [p.strip() for p in args.policies.split(",")] if args.policies else None
    try:
        keys = select_policies(profile, requested)
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    results = generate(profile, keys, args.out, no_llm=args.no_llm)
    for key, md_path, docx_path, used in results:
        tag = "LLM-tailored" if used else "deterministic fallback"
        print(f"  {key:28s} -> {md_path.name}, {docx_path.name}  [{tag}]")
    print(f"\n{len(results)} policy document(s) written to {args.out}/")
    print("All outputs are AI-assisted drafts — review and approve before use.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
